function emailApiPlugin(): Plugin {
  return {
    name: 'vite-plugin-email-api',
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        if (req.url && req.url.startsWith('/api/send-reset-email') && req.method === 'POST') {
          let body = '';
          req.on('data', chunk => {
            body += chunk;
          });
          req.on('end', async () => {
            try {
              const { email, resetLink } = JSON.parse(body || '{}');
              if (!email) {
                res.statusCode = 400;
                res.setHeader('Content-Type', 'application/json');
                res.end(JSON.stringify({ success: false, message: 'Email address is required' }));
                return;
              }
              const { sendPasswordResetEmail } = await import('./server/emailService');
              const result = await sendPasswordResetEmail(email, resetLink);
              res.statusCode = 200;
              res.setHeader('Content-Type', 'application/json');
              res.end(JSON.stringify(result));
            } catch (err: any) {
              res.statusCode = 500;
              res.setHeader('Content-Type', 'application/json');
              res.end(JSON.stringify({ success: false, message: err.message || 'Failed to process email' }));
            }
          });
          return;
        }
        next();
      });
    },
  };
}

